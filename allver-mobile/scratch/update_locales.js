function updateLocales() {
  for (const [lang, newKeys] of Object.entries(translations)) {
    const filePath = path.join(localesDir, `${lang}.json`);
    if (fs.existsSync(filePath)) {
      try {
        const content = fs.readFileSync(filePath, 'utf8');
        const existingData = JSON.parse(content);
        const mergedData = { ...existingData, ...newKeys };
        fs.writeFileSync(filePath, JSON.stringify(mergedData, null, 2) + '\n', 'utf8');
        console.log(`Successfully updated ${lang}.json with new keys.`);
      } catch (err) {
        console.error(`Error processing ${lang}.json:`, err);
      }
    } else {
      console.warn(`File ${lang}.json not found at ${filePath}. Creating new...`);
      try {
        fs.writeFileSync(filePath, JSON.stringify(newKeys, null, 2) + '\n', 'utf8');
        console.log(`Successfully created ${lang}.json.`);
      } catch (err) {
        console.error(`Error creating ${lang}.json:`, err);
      }
    }
  }
}

updateLocales();
